/**
 * 배 위치 수집 일정과 「수집이 죽었나」 판정. **파이어스토어도 브라우저도 모른다** —
 * 그래야 `node scripts/test-sync-schedule.mjs` 로 실제 코드를 그대로 돌려 검증할 수 있다
 * (`sea.ts`·`weather.ts`·`yard-transform.mjs` 와 같은 이유).
 *
 * ★★**균등 주기가 아니면 「주기 x 1.5」 로는 판정할 수 없다** (2026-09-14).
 *  예전에는 6시간 균등(KST 06/12/18/00)이라 `SYNC_PERIOD_H * 90` 한 줄이면 됐다.
 *  업무시간에만 돌게 바꾸면서 **밤 사이 간격이 15시간**이 됐다(17시 → 다음날 8시).
 *  그 규칙을 그대로 두면 **매일 밤 21시 반에 멀쩡한 수집이 빨갛게** 뜬다 — 칩이
 *  지켜야 하는 건 「몇 시간째 그대로」와 「수집이 죽음」을 가르는 것인데, 매일 밤
 *  거짓 빨간불이 뜨면 그 구분이 통째로 무의미해진다.
 *
 *  그래서 「얼마나 오래됐나」가 아니라 **「돌았어야 할 것을 걸렀나」**로 판정한다.
 *  밤에는 다음 예정이 아침 8시이므로 17시 값이 6시간 묵어도 정상이고,
 *  아침 9시 반에 8시 것이 안 들어왔으면 그때는 빨갛다.
 */

/**
 * 수집 회차(KST, 정시). (2026-09-14 사용자 지시: 「오전 8시부터 3시간 단위로 하고 오후 6시에 정지」)
 * ★**일정의 정본은 여기 하나다.** 크론(`.github/workflows/sync-safetyone.yml`)은 매시간
 *  깨우기만 하고, 돌릴지는 아래 `collectDue` 가 이 값을 보고 정한다(2026-11-13).
 *  크론이 이 회차들을 전부 깨우는지는 `scripts/test-sync-schedule.mjs` [4] 가 대조한다.
 */
export const SYNC_HOURS_KST = [8, 11, 14, 17];

/**
 * 크론이 밀리는 것을 감안한 여유(분).
 * 깃허브 **스케줄 워크플로는 부하 때 지연·유실된다** — 정시에 딱 맞춰 판정하면
 * 몇 분 밀릴 때마다 빨개진다.
 *
 * ★★**90분은 재지 않고 찍은 값이었다** (2026-09-14 같은 날 정정).
 *  이 레포의 실제 실행 이력을 재 보니 **최근 5회가 전부 1시간 40분~4시간 41분 늦었다**:
 *
 *  | 예정(KST)  | 실제      | 지연 |
 *  |------------|-----------|------|
 *  | 9/13 06:00 | 07:40     | 1:40 |
 *  | 9/13 12:00 | 16:41     | 4:41 |
 *  | 9/13 18:00 | 22:29     | 4:29 |
 *  | 9/14 00:00 | 02:44     | 2:44 |
 *  | 9/14 06:00 | 07:41     | 1:41 |
 *
 *  즉 90분이면 **다섯 번 다** 「수집이 죽었다」로 빨갛게 떴다 — 멀쩡히 돌고 있는데도.
 *  매일 거짓 빨간불이 뜨면 「좀 늦음」과 「죽음」의 구분이 통째로 무의미해진다.
 *  이 파일이 애초에 막으려던 바로 그 실패를 **숫자 하나로 다시 만들고 있었다.**
 *
 *  ★교훈: **지연 허용치는 "이쯤이면 되겠지" 가 아니라 실제 실행 이력을 재서 정한다.**
 *  실측 최대(4:41 = 281분)를 덮는 **300분**으로 올린다. 트레이드오프는 알고 고른 것이다 —
 *  진짜로 죽었을 때 빨개지는 데 최대 5시간이 걸린다. 회차 간격이 3시간이므로 그 시점이면
 *  **두 회차를 거른 상태**라, 여전히 「한 번 늦음」과 「죽음」은 갈린다.
 */
export const SYNC_SLACK_MIN = 300;

const KST_OFFSET_MIN = 9 * 60;
const DAY_MIN = 24 * 60;

/**
 * 지금 시각 기준으로 **이미 들어왔어야 하는** 가장 최근 수집 시각(ms).
 * 여유(`SYNC_SLACK_MIN`)를 빼고 나서 찾으므로, 방금 시작한 회차는 아직 안 센다.
 */
export function lastDueAt(nowMs: number): number {
  const t = Math.floor(nowMs / 60000) + KST_OFFSET_MIN - SYNC_SLACK_MIN;   // KST 분
  const minOfDay = ((t % DAY_MIN) + DAY_MIN) % DAY_MIN;
  const dayStart = t - minOfDay;
  const hours = [...SYNC_HOURS_KST].sort((a, b) => b - a);                  // 늦은 것부터
  for (const h of hours) if (h * 60 <= minOfDay) return (dayStart + h * 60 - KST_OFFSET_MIN) * 60000;
  // 오늘 것이 아직 하나도 안 왔으면 **어제 마지막 회차**가 기준이다.
  return (dayStart - DAY_MIN + hours[0] * 60 - KST_OFFSET_MIN) * 60000;
}

/** 마지막 확인이 「돌았어야 할 시각」보다 이전이면 한 번은 확실히 거른 것이다 → 빨갛다. */
export function syncIsStale(lastSyncMs: number, nowMs: number): boolean {
  return lastSyncMs < lastDueAt(nowMs);
}

/**
 * 크론이 깨울 때마다 묻는다 — **지금 수집을 돌려야 하나.**
 *
 * ★★**크론은 시계가 아니라 자명종일 뿐이다** (2026-11-13).
 *  크론을 회차 시각(08/11/14/17시 정각)에 맞춰 네 줄 걸어 뒀더니 **하루에 두 번만 돌았다** —
 *  이 레포의 실제 실행 이력(10/28~11/13, 17일 연속): 낮 11:01~13:32 에 한 번, 밤 19:48~22:43 에 한 번.
 *  깃허브가 스케줄을 3~5시간 밀고, 밀린 사이의 회차는 **통째로 버린다.** 그래서 아침에 옮긴
 *  배가 점심에야, 오후에 옮긴 배가 밤 10시에야 지도에 나왔다.
 *  깃허브가 언제 깨워 줄지는 우리가 못 정한다. 정할 수 있는 것은 **깨어났을 때 무엇을 할지**다.
 *  → 크론은 **매시간** 깨우기만 하고(정각을 피해서), 돌릴지는 여기서 정한다:
 *    「가장 최근 회차가 아직 안 채워졌으면 돈다.」
 *
 * ★하루 수집 횟수는 그대로 **최대 4번**이다 — 회차 하나가 수집 한 번을 부르고, 채워진 회차는
 *  다시 안 부른다. 사내 서버를 더 때리지 않는다(자주 깨우는 것 ≠ 자주 긁는 것).
 * ★회차를 놓친 채 `SYNC_SLACK_MIN` 이 지나면 **그 회차는 버린다.** 그 값은 앱이 「걸렀다」고
 *  빨갛게 띄우는 바로 그 시점이다 — 같은 숫자를 써야 「앱은 빨간데 수집은 포기했다」나
 *  「수집은 한밤중에 도는데 앱은 모른다」가 안 생긴다. 그래서 17시 회차는 늦어도 22시 전까지만
 *  메우고, 밤에는 안 돈다(새벽에 깨어나도 다음 회차는 아침 8시다).
 */
export function collectDue(lastSuccessMs: number | null | undefined, nowMs: number): boolean {
  const slack = SYNC_SLACK_MIN * 60000;
  const slot = lastDueAt(nowMs + slack);          // 여유를 뺀 판정을 되돌리면 「방금 시작한 회차」다
  if (nowMs - slot >= slack) return false;        // 이미 놓친 회차 — 다음 회차를 기다린다
  return lastSuccessMs == null || lastSuccessMs < slot;
}

/**
 * ★★**수집이 죽으면 아무도 안 본다** (2026-09-20, 나흘 반 만에 발견).
 *
 * 9/16 10:12(KST) 이후 **15회 연속 실패**했는데 나흘 반 동안 아무 일도 일어나지 않았다.
 * 워크플로는 빨갛게 죽어 있었지만 **그 빨간불이 사용자에게 도달하는 길이 없었다** —
 * 사장님이 9/20 아침에 수집 버튼을 눌렀고 그것도 실패했는데, 화면은 여전히
 * 「위치 확인 N일 전」만 말했다. 「오래됐다」와 **「왜 안 되는지」**는 다른 말이다.
 *
 * 원인은 구조였다: 심장박동을 **성공했을 때만** 남겼다. 그래서 앱이 알 수 있는 것은
 * 「마지막 성공이 언제였나」뿐이고, 실패는 기록 자체가 없었다.
 * → **실패도 남긴다.** 조석 수집에 이미 적용해 둔 규칙과 같다:
 *   **「못 받았다는 기록에는 왜 못 받았는지가 같이 있어야 한다」**.
 *
 * ★**메시지가 아니라 코드만 남긴다.** `meta/safetyone` 은 **공개 읽기**다.
 *  실패 사유 문자열에는 `접속 불가: ${e.message}` 처럼 **사내 주소가 섞여 들어올 수 있다**.
 *  코드(enum)만 남기고 글귀는 앱이 만들면 샐 것이 구조적으로 없다 —
 *  덤으로 「사내 화면 이름은 화면 글귀에 쓰지 않는다」도 저절로 지켜진다.
 */
export type SyncFailCode = 'login' | 'connect' | 'parse' | 'other';

/** 실패 코드 → 화면에 쓸 말. 모르는 코드가 와도 화면이 비지 않게 기본값을 준다. */
export function syncFailLabel(code?: string | null): string {
  switch (code) {
    case 'login':   return '로그인 안 됨';
    case 'connect': return '접속 안 됨';
    case 'parse':   return '화면이 바뀜';
    default:        return '원인 미상';
  }
}

/**
 * 지금 수집이 **깨져 있나.** 마지막 실패가 마지막 성공보다 **새로우면** 그게 현재 상태다.
 * (성공이 더 새로우면 그 실패는 이미 지나간 일이다 — 되살아난 것을 빨갛게 두면 안 된다.)
 */
export function syncIsBroken(lastSuccess: number | null | undefined,
                             lastFailure: number | null | undefined): boolean {
  if (lastFailure == null) return false;
  return lastSuccess == null || lastFailure > lastSuccess;
}
